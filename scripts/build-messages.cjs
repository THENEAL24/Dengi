const currenciesSrc = fs.readFileSync(path.join(__dirname, '../src/lib/currencies.ts'), 'utf8');
for (const match of currenciesSrc.matchAll(/def\('(\w+)',\s*'([^']+)'/g)) {
  const [, code, nameRu] = match;
  ru[`currency.name.${code}`] = nameRu;
  en[`currency.name.${code}`] = currencyNamesEn[code] ?? nameRu;
}

function serialize(obj, varName) {
  const lines = Object.entries(obj).map(
    ([k, v]) => `  '${k.replace(/'/g, "\\'")}': ${JSON.stringify(v)},`,
  );
  return `export const ${varName}: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
}

const outDir = path.join(__dirname, '../src/lib/i18n');
fs.writeFileSync(path.join(outDir, 'messages.ru.ts'), serialize(ru, 'ruMessages'));
fs.writeFileSync(path.join(outDir, 'messages.en.ts'), serialize(en, 'enMessages'));
